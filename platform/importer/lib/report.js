// Writes data/catalog/IMPORT-REPORT.md
const SPOT = ['pb-001', 'pb-005', 'pb-006', 'pb-013', 'pb-031', 'pb-071', 'pb-115', 'pb-154', 'pb-174', 'pb-196', 'pb-207', 'pb-208', 'pb-210',
  'pb-211', 'pb-212', 'pb-213', 'pb-216', 'pb-282', 'pb-288', 'pb-294', 'pb-306', 'pb-313', 'pb-325'];

const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const sideTxt = e => `${e.point}${e.side !== 'C' ? ` (${e.side})` : ''}${e.qualifiers?.length ? ` [${e.qualifiers.join(',')}]` : ''}${e.altPoint ? ` / ${e.altPoint}` : ''}`;

export function writeReport({ data, report, counts, manifest, overrides }) {
  const L = [];
  const p = s => L.push(s);
  p('# Catalog import report');
  p('');
  p(`Generated by \`node importer/run.js\` — catalog version **${manifest.version}** (${manifest.generatedAt}).`);
  p('Regenerate: `node importer/run.js` (needs poppler `pdftotext` and the three PDFs in `data/sources/`); validate: `node importer/validate.js`.');
  p('');
  p('## Sources');
  p('');
  p('| id | file | sha256 | license | page numbering |');
  p('|---|---|---|---|---|');
  for (const s of data.sources) p(`| ${s.id} | ${esc(s.file || '—')} | ${s.sha256 ? '`' + s.sha256.slice(0, 16) + '…`' : '—'} | ${s.license_status} | ${esc(s.pageNumbering || '')} |`);
  p('');
  p('## Counts');
  p('');
  p('| file | records |');
  p('|---|---|');
  for (const [k, v] of Object.entries(counts)) p(`| ${k} | ${v} |`);
  const lvl = l => data.pairs.filter(x => x.level === l);
  p('');
  p(`Pairs: Level 1 = ${lvl(1).length} (numbers ${Math.min(...lvl(1).map(x => x.number))}–${Math.max(...lvl(1).map(x => x.number))}), Level 2 = ${lvl(2).length} (${Math.min(...lvl(2).map(x => x.number))}–${Math.max(...lvl(2).map(x => x.number))}), compendium/unnumbered (\`cx-\`, level 0) = ${lvl(0).length}.`);
  const cats = {};
  for (const x of data.pairs.filter(x => x.level > 0)) cats[x.category] = (cats[x.category] || 0) + 1;
  p(`Numbered pairs by category: ${Object.entries(cats).map(([k, v]) => `${k} ${v}`).join(', ')}.`);
  const kinds = {};
  for (const e of data.entities) kinds[e.kind] = (kinds[e.kind] || 0) + 1;
  p(`Entities by kind: ${Object.entries(kinds).map(([k, v]) => `${k} ${v}`).join(', ')}; with English name: ${data.entities.filter(e => e.name.en).length}/${data.entities.length}.`);
  const pk = {};
  for (const x of data.protocols) pk[x.kind] = (pk[x.kind] || 0) + 1;
  p(`Protocols by kind: ${Object.entries(pk).map(([k, v]) => `${k} ${v}`).join(', ')}.`);
  p(`Symptom vocabulary: ${data.symptoms.length} terms, ${data.symptoms.filter(s => s.name.en).length} with English names; ${data.symptoms.filter(s => s.pairs.length).length} linked to at least one pair.`);
  const pp = data.entities.flatMap(e => e.polePairs);
  p(`Entity pole pairs: ${pp.length}, linked to numbered pairs: ${pp.filter(x => x.pairId?.startsWith('pb-')).length}, to \`cx-\` pairs: ${pp.filter(x => x.pairId?.startsWith('cx-')).length}. Ambiguous pole matches resolved by side/relation preference: ${report.ambiguousPoleMatches}.`);
  p('');
  p('## Validation');
  p('');
  p(report.validation.ok ? '`importer/validate.js`: **OK** — every point / pair / entity / protocol / symptom reference resolves; Level 1 = 1..210 and Level 2 = 211..325 are contiguous.' : `**${report.validation.errors.length} error(s)**:\n\n` + report.validation.errors.map(e => `- ${e}`).join('\n'));
  p('');
  p(`Validator warnings: ${report.validation.warnings.length}.`);
  for (const w of report.validation.warnings.filter(w => /ratings/.test(w))) p(`- ${w}`);
  p('');
  p('## Spot checks (numbered pairs vs. raw source text)');
  p('');
  p('| pair | name (es) | tracking (−) | impact (+) | category | relations | F/P/R | symptoms | source |');
  p('|---|---|---|---|---|---|---|---|---|');
  for (const id of SPOT) {
    const x = data.pairs.find(y => y.id === id);
    if (!x) { p(`| ${id} | MISSING |`); continue; }
    p(`| ${id} | ${esc(x.name.es)} | ${esc(sideTxt(x.tracking))} | ${esc(sideTxt(x.impact))} | ${x.category} | ${esc(x.relations.map(r => r.entity + (r.ordinal ? `(${r.ordinal})` : '')).join(', '))} | ${['F', 'P', 'R'].map(k => x.ratings[k] ?? '–').join('/')} | ${x.symptoms.length}${x.symptoms.length ? ': ' + esc(x.symptoms.slice(0, 4).map(s => s.text.es).join('; ')) + (x.symptoms.length > 4 ? '…' : '') : ''} | ${x.source.doc} p.${x.source.page} |`);
  }
  p('');
  p('Each row above was compared by hand against `pdftotext -layout` output of the cited page (see README, "Spot checks").');
  p('');
  p('## Category assignment');
  p('');
  p('Level 1 regular pairs take the category of their index section ("Pares Biomagnéticos (Virus)" …). The Level 1 "Especiales" section and the whole Level 2 index (which has no section headers in the text layer) are classified by the first rule that applies:');
  p('');
  for (const [k, v] of Object.entries(report.categoryMethod)) p(`- ${k}: ${v}`);
  p('');
  p('## Manual overrides (`importer/overrides.json`)');
  p('');
  for (const o of report.overridesApplied) p(`- ${esc(o)}`);
  for (const [n, o] of Object.entries(overrides.pairs || {})) if (o._why) p(`- pair ${n}: ${esc(o._why)}`);
  for (const b of overrides.blockFixes || []) p(`- block fix: ${esc(b.reason)}`);
  p(`- protocolAliases: ${Object.keys(overrides.protocolAliases || {}).length}; entityAliases: ${Object.keys(overrides.entityAliases || {}).length}; categoryByPair: ${Object.keys(overrides.categoryByPair || {}).length}; pointRefs: ${Object.keys(overrides.pointRefs || {}).length}; protocolItems: ${Object.keys(overrides.protocolItems || {}).length}.`);
  p('');
  p('## Source discrepancies (block title vs. index)');
  p('');
  for (const m of report.indexMismatches) p(`- ${esc(m)}`);
  if (!report.indexMismatches.length) p('None.');
  p('');
  p(`## Unresolved items (${report.unresolved.length})`);
  p('');
  p('Protocol list items that name a point pair with no numbered pair are mapped to a `cx-` pair (level 0) so the protocol stays complete; they are listed here for review. Items that are free text are kept in the protocol `notes`.');
  p('');
  const groups = new Map();
  for (const u of report.unresolved) { const k = u.reason.replace(/mapped to .*/, 'mapped to cx- pair'); if (!groups.has(k)) groups.set(k, []); groups.get(k).push(u); }
  for (const [k, us] of groups) {
    p(`### ${esc(k)} (${us.length})`);
    p('');
    for (const u of us) p(`- \`${esc(u.where)}\`: ${esc(u.item)}${/mapped to/.test(u.reason) ? ` → ${esc(u.reason.replace(/.*mapped to /, ''))}` : ''}`);
    p('');
  }
  p(`## Parser warnings (${report.warnings.length})`);
  p('');
  for (const w of report.warnings) p(`- ${esc(w)}`);
  p('');
  if (report.spot.length) {
    p('## Ambiguous protocol items (several numbered pairs share the same points)');
    p('');
    for (const s of report.spot) p(`- ${esc(s)}`);
    p('');
  }
  p('## Known limitations');
  p('');
  for (const l of LIMITATIONS) p(`- ${l}`);
  p('');
  return L.join('\n');
}

